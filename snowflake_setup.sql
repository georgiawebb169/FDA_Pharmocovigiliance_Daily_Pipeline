-- =============================================================================
-- OPENFDA PHARMACOVIGILANCE PIPELINE: SNOWFLAKE INFRASTRUCTURE SETUP
-- =============================================================================

-- 1. Create Role & Virtual Warehouse
CREATE ROLE IF NOT EXISTS FDA_ROLE;

CREATE WAREHOUSE IF NOT EXISTS FDA_WH 
    WITH WAREHOUSE_SIZE = 'XSMALL' 
    AUTO_SUSPEND = 60 
    AUTO_RESUME = TRUE;

-- 2. Create Database & Pipeline Schemas
CREATE DATABASE IF NOT EXISTS FDA_DB;
CREATE SCHEMA IF NOT EXISTS FDA_DB.RAW;
CREATE SCHEMA IF NOT EXISTS FDA_DB.ENRICHED;
CREATE SCHEMA IF NOT EXISTS FDA_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS FDA_DB.MART;

-- 3. Grant Database Permissions to Role
GRANT USAGE ON WAREHOUSE FDA_WH TO ROLE FDA_ROLE;
GRANT ALL PRIVILEGES ON DATABASE FDA_DB TO ROLE FDA_ROLE;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE FDA_DB TO ROLE FDA_ROLE;
GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE FDA_DB TO ROLE FDA_ROLE;

-- 4. Assign Role to Pipeline User & Attach RSA Public Key
GRANT ROLE FDA_ROLE TO USER <YOUR_SNOWFLAKE_USER>;
ALTER USER <YOUR_SNOWFLAKE_USER> SET DEFAULT_ROLE = FDA_ROLE;
ALTER USER <YOUR_SNOWFLAKE_USER> SET DEFAULT_WAREHOUSE = FDA_WH;

-- Paste the contents of rsa_key.pub (without the BEGIN/END header lines) below:
ALTER USER <YOUR_SNOWFLAKE_USER> SET RSA_PUBLIC_KEY = '<PASTE_RSA_PUBLIC_KEY_HERE>';
